@dataclass(frozen=True)
class EpochPreset:
    name: str
    start_year: int | None
    end_year: int | None
    description: str
    rules: str
    technologies: tuple[str, ...]
    restrictions: dict
    starting_stats: dict


def _starting_stats(
    *,
    treasury: int,
    gdp: int,
    personnel: int,
    technology_level: int,
    readiness: int,
    supply: int,
    industry_level: int,
    resources: dict[str, int],
) -> dict:
    income = max(20, gdp // 50)
    expenses = max(15, income * 4 // 5)
    return {
        "economy": {
            "treasury": treasury,
            "gdp": gdp,
            "income": income,
            "expenses": expenses,
            "inflation": 3,
            "unemployment": 5,
            "growth": 2,
            "debt": 0,
            "tax_revenue": income // 2,
            "industry_level": industry_level,
            "stability": 55,
        },
        "military": {
            "personnel": personnel,
            "units": {"ополчение": personnel} if personnel else {},
            "equipment": {},
            "ammunition": {},
            "budget": max(0, treasury // 20),
            "technology_level": technology_level,
            "readiness": readiness,
            "supply": supply,
        },
        "resources": resources,
    }


