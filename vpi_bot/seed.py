async def seed_guild_defaults(session: AsyncSession, guild_id: int) -> None:
    """Insert missing standard resources and eras without overwriting server customizations."""
    existing_resources = set(
        (
            await session.scalars(
                select(ResourceDefinition.name).where(ResourceDefinition.guild_id == guild_id)
            )
        ).all()
    )
    for name, unit, description in BASE_RESOURCES:
        if name not in existing_resources:
            session.add(
                ResourceDefinition(guild_id=guild_id, name=name, unit=unit, description=description)
            )
    existing_epochs = set(
        (await session.scalars(select(Epoch.name).where(Epoch.guild_id == guild_id))).all()
    )
    for name, description, technologies in DEFAULT_EPOCHS:
        if name not in existing_epochs:
            session.add(
                Epoch(
                    guild_id=guild_id, name=name, description=description, technologies=technologies
                )
            )
    await session.flush()
