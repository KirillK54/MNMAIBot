async def seed_guild_defaults(session: AsyncSession, guild_id: int) -> None:
    """Insert standard resources and fill missing preset data without overwriting customizations."""
    existing_resources = set(
        (
            await session.scalars(
                select(ResourceDefinition.name).where(ResourceDefinition.guild_id == guild_id)
            )
        ).all()
    )
    for name, unit, description in BASE_RESOURCES:
        if name not in existing_resources:
            session.add(
                ResourceDefinition(guild_id=guild_id, name=name, unit=unit, description=description)
            )
    epochs = {
        row.name: row
        for row in (await session.scalars(select(Epoch).where(Epoch.guild_id == guild_id))).all()
    }
    for preset in DEFAULT_EPOCHS:
        epoch = epochs.get(preset.name)
        if epoch is None:
            epoch = Epoch(guild_id=guild_id, name=preset.name)
            session.add(epoch)
            epochs[preset.name] = epoch
        if not epoch.description:
            epoch.description = preset.description
        if epoch.start_year is None:
            epoch.start_year = preset.start_year
        if epoch.end_year is None:
            epoch.end_year = preset.end_year
        if not epoch.rules:
            epoch.rules = preset.rules
        if not epoch.technologies:
            epoch.technologies = list(preset.technologies)
        if not epoch.restrictions:
            epoch.restrictions = dict(preset.restrictions)
        if not epoch.starting_stats:
            epoch.starting_stats = dict(preset.starting_stats)
    await session.flush()
